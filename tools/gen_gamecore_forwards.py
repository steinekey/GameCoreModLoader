"""Generates loader/GameCoreForwards.inc: the export table of the GameCore Mod Loader.

usage: python gen_gamecore_forwards.py <path to dumpbin.exe> > loader/GameCoreForwards.inc

Every export of the real GameCore_XP2_FinalRelease.dll becomes a forwarder to it, with the same
ordinal, except the two the exe looks up by name, which go to the loader's own functions. The real
DLL is found through tools/game_paths.json.
"""
import json, os, re, subprocess, sys

# Exports the loader implements itself: name -> loader function.
OWN = {
    'DllCreateGameContext': 'GcmlCreateGameContext',
    'DllDestroyGameContext': 'GcmlDestroyGameContext',
}
TARGET = 'GameCore_XP2_FinalRelease'

dumpbin = sys.argv[1]
here = os.path.dirname(os.path.abspath(__file__))
game_dir = json.load(open(os.path.join(here, 'game_paths.json')))['gameDir']
core = os.path.join(game_dir, 'DLC', 'Expansion2', 'Binaries', 'Win64', TARGET + '.dll')
out = subprocess.run([dumpbin, '-exports', core], capture_output=True, text=True).stdout

rows = []   # (ordinal, name)
for line in out.splitlines():
    m = re.match(r'\s+(\d+)\s+[0-9A-F]+\s+[0-9A-F]{8}\s+(\S+)', line)
    if m:
        rows.append((int(m.group(1)), m.group(2)))
if not rows or not all(name in dict((n, o) for o, n in rows) for name in OWN):
    sys.exit('exports not found in ' + core)

p = print
p('// SPDX-License-Identifier: AGPL-3.0-only')
p('// GENERATED by tools/gen_gamecore_forwards.py from the exports of %s.dll; do not edit.' % TARGET)
p('// Included once, by GameCoreModLoader.cpp.')
for ordinal, name in rows:
    if name in OWN:
        p('#pragma comment(linker, "/export:%s=%s,@%d")' % (name, OWN[name], ordinal))
    else:
        p('#pragma comment(linker, "/export:%s=%s.%s,@%d")' % (name, TARGET, name, ordinal))
